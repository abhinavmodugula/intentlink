#!/usr/bin/env node
// Reads .env and writes config.local.js (git-ignored) for the extension's service worker.
// Re-run this any time .env changes: `node scripts/gen-config.mjs`
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env");
const outPath = join(root, "config.local.js");

function parseEnv(text) {
  const out = {};
  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

let envText;
try {
  envText = readFileSync(envPath, "utf8");
} catch {
  console.error(`No .env found at ${envPath}. Create one with DEEPSEEK_API_KEY / JEV_API_KEY.`);
  process.exit(1);
}

const env = parseEnv(envText);

// RANK_ENGINE and DEMO_MODE are optional in .env; default here.
const config = {
  RANK_ENGINE: env.RANK_ENGINE || "llm", // "llm" | "jev" | "heuristic"
  DEMO_MODE: env.DEMO_MODE === "true",
  DEEPSEEK_API_KEY: env.DEEPSEEK_API_KEY || "",
  JEV_API_KEY: env.JEV_API_KEY || "",
};

if (!config.DEEPSEEK_API_KEY && config.RANK_ENGINE === "llm") {
  console.warn("Warning: RANK_ENGINE is 'llm' but DEEPSEEK_API_KEY is empty.");
}
if (!config.JEV_API_KEY && config.RANK_ENGINE === "jev") {
  console.warn("Warning: RANK_ENGINE is 'jev' but JEV_API_KEY is empty.");
}

const banner =
  "// GENERATED by scripts/gen-config.mjs from .env — do not edit by hand, do not commit.\n";
const body = `self.LL_CONFIG = ${JSON.stringify(config, null, 2)};\n`;

writeFileSync(outPath, banner + body);
console.log(`Wrote ${outPath} (RANK_ENGINE=${config.RANK_ENGINE}, DEMO_MODE=${config.DEMO_MODE})`);
